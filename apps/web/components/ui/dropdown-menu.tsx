"use client"

import * as React from "react"
import { cn } from "cn"
import { DropdownMenu as DropdownMenuPrimitive } from "radix-ui"
import { useGSAP } from "@gsap/react"
import { useOverlayRoot } from "@/components/ui/overlay-root"
import { popoverIn } from "@/lib/motion"
import { CheckIcon, ChevronRightIcon } from "lucide-react"

function DropdownMenu({
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Root>) {
  return <DropdownMenuPrimitive.Root data-slot="dropdown-menu" {...props} />
}

function DropdownMenuPortal({
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Portal>) {
  return (
    <DropdownMenuPrimitive.Portal data-slot="dropdown-menu-portal" {...props} />
  )
}

function DropdownMenuTrigger({
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Trigger>) {
  return (
    <DropdownMenuPrimitive.Trigger
      data-slot="dropdown-menu-trigger"
      {...props}
    />
  )
}

function DropdownMenuContent({
  className,
  align = "start",
  sideOffset = 4,
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Content>) {
  const ref = React.useRef<HTMLDivElement>(null)
  // Mounts on open: pop in from the trigger (lib/motion popoverIn, springy); close is instant.
  useGSAP(() => {
    const el = ref.current
    if (el) popoverIn(el, getComputedStyle(el).transformOrigin)
  }, { dependencies: [] })
  return (
    <DropdownMenuPrimitive.Portal container={useOverlayRoot()}>
      <DropdownMenuPrimitive.Content
        ref={ref}
        data-slot="dropdown-menu-content"
        sideOffset={sideOffset}
        align={align}
        className={cn("float-glass z-50 max-h-(--radix-dropdown-menu-content-available-height) min-w-55 origin-(--radix-dropdown-menu-content-transform-origin) overflow-x-hidden overflow-y-auto rounded-tile p-1.5 text-popover-foreground", className )}
        {...props}
      />
    </DropdownMenuPrimitive.Portal>
  )
}

